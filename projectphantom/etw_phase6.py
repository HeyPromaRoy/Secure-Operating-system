def analyze_timing_sidechannel(samples, label):
    """
    Analyzes sample timestamps to detect scheduler jitter.

    Theory (Chronos v2 connection):
    When ETW is healthy the kernel processes events normally
    and our Python sampler runs at consistent 2-second intervals.

    When EtwEventWrite is patched the kernel encounters the
    patched RET instruction and has to handle the unexpected
    return differently. This creates measurable scheduling
    irregularities that show up as jitter in our timestamps.

    This is a user-space observable timing side-channel —
    we detect kernel-level tampering without kernel access.
    Directly inspired by Chronos v2 scheduler timing attacks.
    """
    if len(samples) < 3:
        print(f"  [-] Not enough samples for timing analysis: {len(samples)}")
        return None

    # extract timestamps from each sample
    timestamps = []
    for s in samples:
        try:
            ts = datetime.datetime.strptime(
                s['timestamp'],
                "%Y-%m-%d %H:%M:%S.%f")
            timestamps.append(ts)
        except (ValueError, KeyError):
            continue

    if len(timestamps) < 3:
        print(f"  [-] Could not parse timestamps")
        return None

    # calculate intervals between consecutive samples
    # these should all be approximately 2.0 seconds
    intervals = []
    for i in range(1, len(timestamps)):
        delta = (timestamps[i] - timestamps[i-1]).total_seconds()
        intervals.append(delta)

    # statistical analysis of intervals
    avg_interval   = statistics.mean(intervals)
    stdev_interval = statistics.stdev(intervals)
    min_interval   = min(intervals)
    max_interval   = max(intervals)
    max_jitter     = max_interval - min_interval
    median_interval = statistics.median(intervals)

    # detect anomaly — high stdev means irregular scheduling
    timing_anomaly = stdev_interval > TIMING_ANOMALY_THRESHOLD

    # calculate coefficient of variation (CV)
    # CV = stdev/mean — normalized measure of variability
    # higher CV during tampering suggests kernel interference
    cv = (stdev_interval / avg_interval) * 100 if avg_interval > 0 else 0

    result = {
        "label"             : label,
        "sample_count"      : len(intervals),
        "avg_interval_sec"  : round(avg_interval, 4),
        "median_interval_sec": round(median_interval, 4),
        "stdev_interval_sec": round(stdev_interval, 4),
        "min_interval_sec"  : round(min_interval, 4),
        "max_interval_sec"  : round(max_interval, 4),
        "max_jitter_sec"    : round(max_jitter, 4),
        "coeff_variation_pct": round(cv, 2),
        "timing_anomaly"    : timing_anomaly,
        "all_intervals"     : [round(x, 4) for x in intervals]
    }

    # print results
    print_subheader(f"Timing Analysis: {label}")
    print(f"  Samples analyzed         : {len(intervals)}")
    print(f"  Expected interval        : 2.0000 sec")
    print(f"  Average interval         : {avg_interval:.4f} sec")
    print(f"  Median interval          : {median_interval:.4f} sec")
    print(f"  Std deviation            : {stdev_interval:.4f} sec")
    print(f"  Min interval             : {min_interval:.4f} sec")
    print(f"  Max interval             : {max_interval:.4f} sec")
    print(f"  Max jitter               : {max_jitter:.4f} sec")
    print(f"  Coefficient of variation : {cv:.2f}%")
    print()

    if timing_anomaly:
        print(f"  [!] TIMING ANOMALY DETECTED")
        print(f"  [!] Stdev {stdev_interval:.4f} exceeds threshold {TIMING_ANOMALY_THRESHOLD}")
        print(f"  [!] Irregular kernel scheduling detected")
    else:
        print(f"  [+] No timing anomaly — scheduling is consistent")

    return result


