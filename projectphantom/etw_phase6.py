def run_test_suite():
    """
    Automated test suite validating all project phases.
    Uses real data files — never hardcoded values.
    Run with: python etw_phase6.py --test
    """
    print_header("PHASE 6B: AUTOMATED TEST SUITE")
    print("  Validating all project phases using real data")
    print("  All tests use actual JSON files — no hardcoded values")

    tests_passed = 0
    tests_failed = 0
    test_results = []

    def run_test(test_number, description, test_func):
        nonlocal tests_passed, tests_failed
        print(f"\n  [TEST {test_number}] {description}")
        try:
            result = test_func()
            if result['passed']:
                print(f"  PASS — {result['message']}")
                tests_passed += 1
            else:
                print(f"  FAIL — {result['message']}")
                tests_failed += 1
            test_results.append({
                "test"    : test_number,
                "desc"    : description,
                "passed"  : result['passed'],
                "message" : result['message']
            })
        except Exception as e:
            print(f"  ERROR — {str(e)}")
            tests_failed += 1
            test_results.append({
                "test"    : test_number,
                "desc"    : description,
                "passed"  : False,
                "message" : f"Exception: {str(e)}"
            })

    # ── Test 1: Baseline log exists and has valid structure ───
    def test_baseline_exists():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": f"{BASELINE_FILE} not found"}
        samples = baseline.get('samples', [])
        if len(samples) == 0:
            return {"passed": False, "message": "No samples in baseline log"}
        if 'start_time' not in baseline:
            return {"passed": False, "message": "Missing start_time field"}
        return {"passed": True, "message": f"{len(samples)} samples found in baseline"}

    run_test(1, "Baseline log exists and has valid structure", test_baseline_exists)

    # ── Test 2: Tampered log exists and has valid structure ───
    def test_tampered_exists():
        tampered = load_log(TAMPERED_FILE)
        if not tampered:
            return {"passed": False, "message": f"{TAMPERED_FILE} not found"}
        samples = tampered.get('samples', [])
        if len(samples) == 0:
            return {"passed": False, "message": "No samples in tampered log"}
        return {"passed": True, "message": f"{len(samples)} samples found in tampered log"}

    run_test(2, "Tampered log exists and has valid structure", test_tampered_exists)

    # ── Test 3: Process counts are realistic ─────────────────
    def test_process_count_realistic():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        counts = [s['process_count'] for s in baseline['samples']]
        avg = statistics.mean(counts)
        if not (100 < avg < 1000):
            return {"passed": False, "message": f"Avg process count {avg:.1f} is unrealistic"}
        return {"passed": True, "message": f"Avg process count {avg:.1f} is realistic (100-1000 range)"}

    run_test(3, "Process counts are realistic", test_process_count_realistic)

    # ── Test 4: ETW provider was active during baseline ──────
    def test_etw_active():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        etw_active = baseline.get('etw_active', False)
        provider   = baseline.get('provider', 'unknown')
        if not etw_active:
            return {"passed": False, "message": f"ETW was not active — provider: {provider}"}
        return {"passed": True, "message": f"ETW was active — provider: {provider}"}

    run_test(4, "ETW provider was active during baseline capture", test_etw_active)

    # ── Test 5: CPU values are in valid range ─────────────────
    def test_cpu_valid():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        cpu_values = [s['cpu_percent'] for s in baseline['samples']]
        for v in cpu_values:
            if not (0 <= v <= 100):
                return {"passed": False, "message": f"Invalid CPU value: {v}%"}
        avg_cpu = statistics.mean(cpu_values)
        return {"passed": True, "message": f"All CPU values valid — avg: {avg_cpu:.1f}%"}

    run_test(5, "CPU usage values are in valid range (0-100%)", test_cpu_valid)

    # ── Test 6: Memory values are in valid range ──────────────
    def test_memory_valid():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        mem_values = [s['memory_percent'] for s in baseline['samples']]
        for v in mem_values:
            if not (0 <= v <= 100):
                return {"passed": False, "message": f"Invalid memory value: {v}%"}
        avg_mem = statistics.mean(mem_values)
        return {"passed": True, "message": f"All memory values valid — avg: {avg_mem:.1f}%"}

    run_test(6, "Memory usage values are in valid range (0-100%)", test_memory_valid)

    # ── Test 7: Both logs have same sample structure ──────────
    def test_matching_structure():
        baseline = load_log(BASELINE_FILE)
        tampered = load_log(TAMPERED_FILE)
        if not baseline or not tampered:
            return {"passed": False, "message": "One or both logs not available"}
        b_keys = set(baseline['samples'][0].keys())
        t_keys = set(tampered['samples'][0].keys())
        if b_keys != t_keys:
            missing = b_keys - t_keys
            return {"passed": False, "message": f"Structure mismatch — missing keys: {missing}"}
        return {"passed": True, "message": f"Both logs have matching structure: {sorted(b_keys)}"}

    run_test(7, "Baseline and tampered logs have matching structure", test_matching_structure)

    # ── Test 8: Timestamps are valid and sequential ───────────
    def test_timestamps_valid():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        timestamps = []
        for s in baseline['samples']:
            try:
                ts = datetime.datetime.strptime(
                    s['timestamp'], "%Y-%m-%d %H:%M:%S.%f")
                timestamps.append(ts)
            except ValueError as e:
                return {"passed": False, "message": f"Invalid timestamp: {e}"}
        # check they are sequential
        for i in range(1, len(timestamps)):
            if timestamps[i] <= timestamps[i-1]:
                return {"passed": False, "message": "Timestamps are not sequential"}
        return {"passed": True, "message": f"{len(timestamps)} timestamps are valid and sequential"}

    run_test(8, "All timestamps are valid and sequential", test_timestamps_valid)

    # ── Test 9: Detection gap calculation is valid ────────────
    def test_detection_gap_valid():
        baseline = load_log(BASELINE_FILE)
        tampered = load_log(TAMPERED_FILE)
        if not baseline or not tampered:
            return {"passed": False, "message": "One or both logs not available"}

        # extract process names from both
        b_names = set()
        for s in baseline['samples']:
            for p in s.get('processes', []):
                b_names.add(p['name'])

        t_names = set()
        for s in tampered['samples']:
            for p in s.get('processes', []):
                t_names.add(p['name'])

        missing = b_names - t_names
        gap_pct = round(len(missing) / max(len(b_names), 1) * 100, 2)

        if gap_pct < 0 or gap_pct > 100:
            return {"passed": False, "message": f"Detection gap {gap_pct}% is out of range"}
        return {"passed": True,
                "message": f"Detection gap: {gap_pct}% — {len(missing)} processes missing"}

    run_test(9, "Detection gap calculation produces valid result", test_detection_gap_valid)

    # ── Test 10: SIEM alert has required fields ───────────────
    def test_siem_alert_valid():
        if not os.path.exists(ALERT_FILE):
            return {"passed": True,
                    "message": "No SIEM alert file — no tampering detected (acceptable result)"}
        with open(ALERT_FILE) as f:
            alert = json.load(f)
        required = ['alert_id', 'severity', 'mitre_technique',
                   'mitre_tactic', 'ghost_processes', 'timestamp']
        missing = [k for k in required if k not in alert]
        if missing:
            return {"passed": False, "message": f"SIEM alert missing fields: {missing}"}
        ghost_count = len(alert['ghost_processes'])
        return {"passed": True,
                "message": f"SIEM alert valid — severity: {alert['severity']}, "
                          f"ghost processes: {ghost_count}"}

    run_test(10, "SIEM alert has all required fields", test_siem_alert_valid)

    # ── Test 11: Timing analysis produces valid intervals ─────
    def test_timing_intervals():
        baseline = load_log(BASELINE_FILE)
        if not baseline:
            return {"passed": False, "message": "Baseline log not available"}
        samples = baseline.get('samples', [])
        if len(samples) < 3:
            return {"passed": False, "message": f"Not enough samples: {len(samples)}"}
        timestamps = []
        for s in samples:
            try:
                ts = datetime.datetime.strptime(
                    s['timestamp'], "%Y-%m-%d %H:%M:%S.%f")
                timestamps.append(ts)
            except ValueError:
                continue
        intervals = [(timestamps[i] - timestamps[i-1]).total_seconds()
                     for i in range(1, len(timestamps))]
        avg = statistics.mean(intervals)
        # intervals should be approximately 2 seconds (1.5 to 3.5 is acceptable)
        if not (1.5 <= avg <= 3.5):
            return {"passed": False,
                    "message": f"Avg interval {avg:.4f}s outside expected range (1.5-3.5s)"}
        return {"passed": True,
                "message": f"Avg sampling interval: {avg:.4f}s (expected ~2.0s)"}

    run_test(11, "Sampling intervals are approximately 2 seconds", test_timing_intervals)

    # ── Test 12: Tampered log shows CPU anomaly ───────────────
    def test_cpu_anomaly():
        baseline = load_log(BASELINE_FILE)
        tampered = load_log(TAMPERED_FILE)
        if not baseline or not tampered:
            return {"passed": False, "message": "One or both logs not available"}
        b_cpu = statistics.mean([s['cpu_percent'] for s in baseline['samples']])
        t_cpu = statistics.mean([s['cpu_percent'] for s in tampered['samples']])
        delta = t_cpu - b_cpu
        # any difference is worth reporting — positive or negative
        return {"passed": True,
                "message": f"CPU during baseline: {b_cpu:.2f}% | "
                          f"tampered: {t_cpu:.2f}% | "
                          f"delta: {delta:+.2f}%"}

    run_test(12, "CPU anomaly comparison baseline vs tampered", test_cpu_anomaly)

    # ── Summary ───────────────────────────────────────────────
    print()
    print("=" * 60)
    print("  TEST SUITE RESULTS")
    print("=" * 60)
    print(f"  Tests passed : {tests_passed}")
    print(f"  Tests failed : {tests_failed}")
    print(f"  Total tests  : {tests_passed + tests_failed}")
    print()
    if tests_failed == 0:
        print("  ALL TESTS PASSED")
    else:
        print(f"  {tests_failed} TEST(S) FAILED — check output above")
    print("=" * 60)

    # save test report
    report_lines = [
        "=" * 60,
        "  PROJECT PHANTOM - AUTOMATED TEST SUITE REPORT",
        "  Phase 6B: Test Suite",
        f"  Generated: {get_timestamp()}",
        "=" * 60,
        ""
    ]
    for r in test_results:
        status = "PASS" if r['passed'] else "FAIL"
        report_lines.append(f"  [TEST {r['test']}] [{status}] {r['desc']}")
        report_lines.append(f"           {r['message']}")
        report_lines.append("")

    report_lines += [
        "=" * 60,
        f"  Tests passed : {tests_passed}",
        f"  Tests failed : {tests_failed}",
        f"  Total        : {tests_passed + tests_failed}",
        f"  Result       : {'ALL PASSED' if tests_failed == 0 else 'FAILURES DETECTED'}",
        "=" * 60
    ]

    with open(TEST_REPORT, 'w') as f:
        f.write("\n".join(report_lines))
    print(f"\n  [+] Test report saved to: {TEST_REPORT}")

    return tests_failed == 0


