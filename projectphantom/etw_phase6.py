    """
    Main Phase 6A function.
    Runs timing side-channel analysis on both baseline
    and tampered logs and compares the results.
    """
    print_header("PHASE 6A: TIMING SIDE-CHANNEL ANALYSIS")
    print("  Connecting Chronos v2 concepts to Project Phantom")
    print("  Detecting ETW tampering through scheduler jitter")

    # load both logs
    baseline = load_log(BASELINE_FILE)
    tampered = load_log(TAMPERED_FILE)

    if not baseline:
        print(f"\n  [-] Baseline log not found: {BASELINE_FILE}")
        print("  [-] Run Phase 2 first to generate baseline data")
